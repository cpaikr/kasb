import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import ts from "typescript";

const repositoryRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const configPath = resolve(repositoryRoot, "packages/node/tsconfig.json");
const config = ts.readConfigFile(configPath, ts.sys.readFile);
if (config.error) throw new Error(ts.flattenDiagnosticMessageText(config.error.messageText, "\n"));
const parsed = ts.parseJsonConfigFileContent(config.config, ts.sys, resolve(repositoryRoot, "packages/node"));
const program = ts.createProgram(parsed.fileNames, parsed.options);
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length > 0) {
  throw new Error(ts.formatDiagnosticsWithColorAndContext(diagnostics, {
    getCanonicalFileName: (path) => path,
    getCurrentDirectory: () => repositoryRoot,
    getNewLine: () => "\n",
  }));
}
const checker = program.getTypeChecker();
const declarations = [
  ["search-standards", "SearchStandardsRawInput", "SearchStandardsInput", "SearchStandardsResult"],
  ["get-standard-structure", "GetStandardStructureRawInput", "GetStandardStructureInput", "GetStandardStructureResult"],
  ["get-section", "GetSectionRawInput", "GetSectionInput", "GetSectionResult"],
  ["get-paragraph", "GetParagraphRawInput", "GetParagraphInput", "GetParagraphResult"],
  ["search-qna", "SearchQnaRawInput", "SearchQnaInput", "SearchQnaResult"],
  ["get-qna", "GetQnaRawInput", "GetQnaInput", "GetQnaResult"],
];
const lines = [
  "// Generated by scripts/generate-node-sdk-declarations.mjs from the Node-owned v1 contract projection.",
  "export type KasbExecutionContext = {",
  "  readonly signal?: AbortSignal;",
  "};",
  "",
];

for (const [directory, inputAlias, publicInput, resultAlias] of declarations) {
  const sourcePath = resolve(repositoryRoot, `packages/node/src/capabilities/${directory}/contract.ts`);
  const source = program.getSourceFile(sourcePath);
  if (!source) throw new Error(`TypeScript program did not include ${sourcePath}`);
  lines.push(`export type ${publicInput} = ${typeText(source, inputAlias)};`, "");
  lines.push(`export type ${resultAlias} = ${typeText(source, resultAlias)};`, "");
}

lines.push(
  "export type KasbFailureCode =",
  '  | "invalid_input"',
  '  | "not_found"',
  '  | "source_unavailable"',
  '  | "source_changed"',
  '  | "partial_retrieval"',
  '  | "internal_failure";',
  "",
  "export type KasbFailureDetails = {",
  "  readonly code: KasbFailureCode;",
  "  readonly message: string;",
  "  readonly retryable: boolean;",
  "  readonly parameter?: string;",
  "  readonly sourceUrl?: string;",
  "};",
  "",
  "export declare class KasbFailure extends Error {",
  '  readonly name: "KasbFailure";',
  "  readonly code: KasbFailureCode;",
  "  readonly retryable: boolean;",
  "  readonly parameter?: string;",
  "  readonly sourceUrl?: string;",
  "  constructor(details: KasbFailureDetails);",
  "}",
  "",
  "export declare function searchStandards(input: SearchStandardsInput, context?: KasbExecutionContext): Promise<SearchStandardsResult>;",
  "export declare function getStandardStructure(input: GetStandardStructureInput, context?: KasbExecutionContext): Promise<GetStandardStructureResult>;",
  "export declare function getSection(input: GetSectionInput, context?: KasbExecutionContext): Promise<GetSectionResult>;",
  "export declare function getParagraph(input: GetParagraphInput, context?: KasbExecutionContext): Promise<GetParagraphResult>;",
  "export declare function searchQna(input: SearchQnaInput, context?: KasbExecutionContext): Promise<SearchQnaResult>;",
  "export declare function getQna(input: GetQnaInput, context?: KasbExecutionContext): Promise<GetQnaResult>;",
  "",
);

const unformatted = lines.join("\n");
const declarationFile = ts.createSourceFile(
  "index.d.ts",
  unformatted,
  ts.ScriptTarget.Latest,
  true,
  ts.ScriptKind.TS,
);
const output = `${ts.createPrinter({ newLine: ts.NewLineKind.LineFeed }).printFile(declarationFile).trimEnd()}\n`;
const outputPath = resolve(repositoryRoot, "packages/node/src/index.d.ts");
if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8");
  if (current !== output) throw new Error("packages/node/src/index.d.ts is stale");
  console.log("Node SDK declarations are current");
} else {
  await writeFile(outputPath, output);
  console.log("generated Node SDK declarations");
}

function typeText(source, aliasName) {
  const declaration = source.statements.find((statement) =>
    ts.isTypeAliasDeclaration(statement) && statement.name.text === aliasName
  );
  if (!declaration) throw new Error(`Missing type alias ${aliasName} in ${source.fileName}`);
  const type = checker.getTypeAtLocation(declaration);
  return checker.typeToString(
    type,
    declaration,
    ts.TypeFormatFlags.NoTruncation
      | ts.TypeFormatFlags.InTypeAlias
      | ts.TypeFormatFlags.MultilineObjectLiterals,
  );
}
